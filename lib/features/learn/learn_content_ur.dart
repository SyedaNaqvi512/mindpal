/// The article's text in [lang] ('en' or 'ur'); English if no Urdu text exists.
ArticleText articleText(Article a, String lang) {
  if (lang == 'ur') {
    final ur = kArticlesUr[a.id];
    if (ur != null) return ur;
  }
  return ArticleText(title: a.title, summary: a.summary, blocks: a.blocks);
}
